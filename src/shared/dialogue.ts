let lastLine = ''

/** 事件 → 阴阳怪气台词（避免连续重复同一句） */
export function line(event: DialogueEvent, ctx: DialogueContext = {}): string {
  const pool = pools[event] ?? pools.click
  let pick = pool[Math.floor(Math.random() * pool.length)]
  if (pool.length > 1 && pick === lastLine) {
    pick = pool[(pool.indexOf(pick) + 1) % pool.length]
  }
  lastLine = pick
  return pick.replace(/\{(\w+)\}/g, (_, key: string) => String(ctx[key] ?? ''))
}
